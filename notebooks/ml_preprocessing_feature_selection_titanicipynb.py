from math import log2

feature = train_data["sex"].tolist()
target = train_data["survived"].tolist()

# Function to calculate entropy
def entropy(values):
    counts = {}

    for value in values:
        counts[value] = counts.get(value, 0) + 1

    total = len(values)
    result = 0

    for count in counts.values():
        probability = count / total
        result -= probability * log2(probability)

    return result


# Entropy of target
H_Y = entropy(target)

# Calculate conditional entropy H(Y|X)
conditional_entropy = 0

categories = set(feature)

for category in categories:

    target_subset = []

    for i in range(len(feature)):
        if feature[i] == category:
            target_subset.append(target[i])

    probability_x = len(target_subset) / len(feature)

    conditional_entropy += (
        probability_x * entropy(target_subset)
    )


# Mutual Information
mutual_information = H_Y - conditional_entropy

print("Entropy of Target:", H_Y)
