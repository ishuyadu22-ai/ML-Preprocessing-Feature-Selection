# Function to calculate percentile
def percentile_from_scratch(values, p):
    n = len(values)
    position = (n - 1) * p

    lower = int(position)
    upper = lower + 1

    if upper >= n:
        return values[lower]

    weight = position - lower

    return values[lower] + weight * (values[upper] - values[lower])


