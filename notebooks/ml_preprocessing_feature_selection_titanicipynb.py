# Calculate Chi-Square statistic
chi_square = 0

for category in categories:
    for target_value in target_values:

        expected = (
            row_totals[category] *
            column_totals[target_value]
        ) / grand_total

        actual = observed[category][target_value]

        if expected != 0:
            chi_square += ((actual - expected) ** 2) / expected


