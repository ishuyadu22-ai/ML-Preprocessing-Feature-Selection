# ---------------- MEDIAN ----------------
def median_from_scratch(values):
    values = sorted(values)
    n = len(values)

    if n % 2 == 1:
        return values[n // 2]
    else:
        return (values[n // 2 - 1] + values[n // 2]) / 2


# ---------------- MODE ----------------
def mode_from_scratch(values):
    frequency = {}

    for x in values:
        frequency[x] = frequency.get(x, 0) + 1

    max_frequency = max(frequency.values())

    modes = [x for x, count in frequency.items()
             if count == max_frequency]

    return modes


# ---------------- VARIANCE ----------------
def variance_from_scratch(values):
    mean = sum(values) / len(values)

    squared_diff = 0
    for x in values:
        squared_diff += (x - mean) ** 2

    return squared_diff / (len(values) - 1)


# ---------------- STANDARD DEVIATION ----------------
def std_from_scratch(values):
    return variance_from_scratch(values) ** 0.5


# ---------------- RANGE ----------------
def range_from_scratch(values):
    return max(values) - min(values)


